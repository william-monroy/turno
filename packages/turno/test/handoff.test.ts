import { mkdirSync, symlinkSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { buildHandoff } from "../src/cli/commands/handoff.js";
import { type Sandbox, sandbox } from "./helpers/sandbox.js";

let sb: Sandbox;
beforeEach(() => {
  sb = sandbox();
  mkdirSync(join(sb.home, ".claude/projects/-w-acme"), { recursive: true });
  for (const p of ["work", "personal"]) {
    mkdirSync(join(sb.home, `.claude-${p}`), { recursive: true });
    symlinkSync(join(sb.home, ".claude/projects"), join(sb.home, `.claude-${p}/projects`));
    sb.write(`.local/bin/claude-${p}`, "#!/bin/sh\n# Generated by turno\n", 0o755);
  }
  mkdirSync(join(sb.home, ".claude-solo"), { recursive: true });
  sb.write(".local/bin/claude-solo", "#!/bin/sh\n# Generated by turno\n", 0o755);
  sb.write(".claude/projects/-w-acme/s1.jsonl", '{"type":"summary"}\n{"cwd":"/w/acme repo","type":"user"}\n{"cwd":"/w/other"}\n');
});
afterEach(() => sb.cleanup());

describe("handoff", () => {
  const env = () => ({ ...sb.env, CLAUDE_CODE_SESSION_ID: "s1", CLAUDE_CONFIG_DIR: join(sb.home, ".claude-work") });

  it("builds resume and fork commands from the first recorded folder", () => {
    expect(buildHandoff("personal", false, env()).command).toBe("cd '/w/acme repo' && turno personal --resume s1");
    expect(buildHandoff("auto", true, env()).command).toBe("cd '/w/acme repo' && turno auto --resume s1 --fork-session");
  });

  it("warns when the target cannot see the session and rejects unknown profiles", () => {
    expect(buildHandoff("solo", false, env()).warnings.join()).toContain("does not share the projects folder");
    expect(buildHandoff("work", false, env()).warnings.join()).toContain("already runs as");
    expect(() => buildHandoff("nope", false, env())).toThrow(/no profile/);
    expect(() => buildHandoff("work", false, sb.env)).toThrow(/CLAUDE_CODE_SESSION_ID/);
  });
});
