import { mkdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { type Check, collectChecks, doctor } from "../src/cli/commands/doctor.js";
import { writeLauncher } from "../src/cli/launchers.js";
import { main } from "../src/cli/main.js";
import { securityChecks } from "../src/cli/security.js";
import { tokenSyncCheck } from "../src/mcpd/health.js";
import { fakeCommand, fakeIo } from "./helpers/cli.js";
import { freePort } from "./helpers/net.js";
import { type Sandbox, sandbox } from "./helpers/sandbox.js";

let sb: Sandbox;

beforeEach(async () => {
  sb = sandbox();
  // Only the sandbox's own commands: no real codex, copilot or cursor-agent from this machine.
  sb.env.PATH = `${join(sb.home, ".local/bin")}:/usr/bin:/bin`;
  sb.env.TURNO_CHROME_APP = join(sb.home, "no-chrome.app");
  fakeCommand(sb, "claude", `echo '{"loggedIn":false}'`);
  const port = await freePort();
  sb.write(
    ".config/turno/config.toml",
    [`[mcpd]\nport = ${port}`, '[profiles.work]\ncolor = "blue"', "[profiles.personal]", '[profiles.cx]\nagent = "codex"', '[[projects]]\npath = "~/x"\nprofile = "ghost"'].join("\n\n"),
  );
  mkdirSync(join(sb.home, ".claude"), { recursive: true });
  for (const name of ["work", "personal"]) mkdirSync(join(sb.home, `.claude-${name}`), { recursive: true });
  writeLauncher("work", sb.env);
  // A launcher turno did not write: only a person can decide what to do with it.
  sb.write(".local/bin/claude-personal", "#!/bin/sh\nexec claude\n", 0o755);
  sb.write(".local/state/turno/version", "0.0.1\n");
  sb.write(
    ".config/turno/mcp.toml",
    ['[server.gh]\ncommand = "gh-mcp"\nenv = { GITHUB_TOKEN = "keychain:gh" }', '[server.loose]\ncommand = "loose-mcp"\npackage = "loose-mcp@^1.2.0"'].join("\n\n"),
    0o600,
  );
});
afterEach(() => sb.cleanup());

const problems = (checks: Check[]) => checks.filter((c) => c.level === "warn" || c.level === "fail");

describe("turno doctor names the fix for every finding", () => {
  it("gives every warning and failure a command or a manual step, and keeps it out of the text", async () => {
    const all = [...(await collectChecks(sb.env)), ...(await securityChecks(sb.env))];
    expect(problems(all).length).toBeGreaterThan(4);
    for (const c of problems(all)) {
      expect(Boolean(c.fix || c.hint || c.manual), c.text).toBe(true);
      expect(c.text, c.text).not.toMatch(/\((turno|npm) [^)]*\)$/);
    }
    const by = (part: string) => all.find((c) => c.text.includes(part));
    expect(by("codex not found on PATH")).toMatchObject({ level: "fail", hint: "npm install --global @openai/codex" });
    expect(by("was not generated by turno")?.manual).toBe("move ~/.local/bin/claude-personal aside (it is yours, so turno does not overwrite it), then turno profile repair personal");
    expect(by("uses profile ghost")).toMatchObject({ level: "warn", hint: "turno profile add ghost" });
    expect(by("set up the launchers")?.fix?.label).toBe("turno upgrade --finish");
  });

  it("config.toml findings name turno profile add or the line to edit", async () => {
    sb.write(
      ".config/turno/config.toml",
      [
        'defualt = "work"',
        'fallback = "cx"',
        'zzz_unknown = 1',
        "[profiles.work]",
        'colour = "blue"',
        '[profiles.cx]\nagent = "codex"',
        "[agents.codex]",
        'default = "work"',
        '[[projects]]\npath = "~/a"\nprofile = "work"',
        '[[projects]]\npath = "~/x"\nprofile = "ghost"\nmcp = ["gh", "lose", "zzz"]',
      ].join("\n"),
    );
    const config = (await collectChecks(sb.env)).filter((c) => c.area === "config" && c.level === "warn");
    const by = (part: string) => config.find((c) => c.text.includes(part));
    const file = "~/.config/turno/config.toml";
    expect(by("unknown key defualt")).toMatchObject({ manual: `edit ${file} line 1: rename it to default` });
    expect(by("unknown key zzz_unknown")).toMatchObject({ manual: `edit ${file} line 3: remove it` });
    expect(by("unknown key profiles.work.colour")).toMatchObject({ manual: `edit ${file} line 5: rename it to color` });
    expect(by('fallback = "cx"')).toMatchObject({ text: 'fallback = "cx" is for Claude Code, but cx is a Codex CLI profile', manual: `edit ${file} line 2: move it to [agents.codex]` });
    expect(by("agents.codex.default")).toMatchObject({ manual: `edit ${file} line 9: name a Codex CLI profile` });
    expect(by("uses profile ghost")).toMatchObject({ text: "the rule for ~/x uses profile ghost, which does not exist", hint: "turno profile add ghost" });
    expect(by('"lose"')).toMatchObject({ text: 'the rule for ~/x lists "lose" in mcp, which is not in mcp.toml (did you mean loose?)', manual: `edit ${file} line 16: write loose` });
    expect(by('"zzz"')).toMatchObject({ manual: `edit ${file} line 16: remove "zzz", or declare it in mcp.toml` });
    for (const c of config) expect(c.text, c.text).not.toContain("turno profile list");
    const io = fakeIo(sb.env);
    await doctor(io);
    expect(io.lines.join("\n")).toContain(`  !  unknown key defualt (did you mean default?); turno ignores it\n     manual: edit ${file} line 1: rename it to default\n`);
    expect(io.lines.join("\n")).toContain("  !  the rule for ~/x uses profile ghost, which does not exist\n     fix: turno profile add ghost\n");
  });

  it("prints sections with one row per check, a fix line under each problem and a summary", async () => {
    const io = fakeIo(sb.env);
    expect(await doctor(io)).toBe(1);
    const out = io.lines.join("\n");
    for (const section of ["System", "Config", "Profiles", "Look", "Gateway"]) expect(io.lines).toContain(section);
    expect(out).toContain("  x  codex not found on PATH, and profiles use it\n     fix: npm install --global @openai/codex\n");
    expect(out).toMatch(/ {2}! {2}turno \S+ runs, but 0\.0\.1 set up the launchers\n {5}fix: turno upgrade --finish \(turno doctor --fix runs it\)/);
    expect(out).toMatch(/ {2}x {2}personal +~\/\.local\/bin\/claude-personal was not generated by turno\n {5}manual: move /);
    expect(out).toMatch(/^\d+ ok, \d+ warnings?, \d+ failures?, \d+ skipped in \d+(ms|\.\ds)$/m);
    expect(out).toMatch(/^Next {2}turno doctor --fix {2}repairs \d+ of \d+; the others name their fix above$/m);
  });

  it("draws icons, rules and profile pills on a terminal", async () => {
    const io = { ...fakeIo({ ...sb.env, COLUMNS: "100" }), isTty: true };
    await doctor(io);
    const out = io.lines.join("\n");
    expect(out).toContain("\x1b[1mSystem\x1b[0m \x1b[90m───");
    expect(out).toContain("\x1b[31m✗\x1b[0m");
    // work is blue (25); its pill opens its rows and later rows leave the column blank.
    expect(out).toContain("\x1b[48;5;25;1;38;5;255m work \x1b[0m");
    expect(io.lines.filter((l) => l.includes(" work \x1b[0m")).length).toBe(1);
  });

  it("--json adds status, fix, auto and manual per check, and counts, ms and next", async () => {
    const io = fakeIo(sb.env);
    expect(await doctor(io, { json: true })).toBe(1);
    const data = JSON.parse(io.lines.join("\n"));
    expect(data.ok).toBe(false);
    expect(Object.keys(data.counts)).toEqual(["ok", "warn", "fail", "skip"]);
    expect(typeof data.ms).toBe("number");
    for (const c of data.checks) {
      expect(Object.keys(c)).toEqual(["area", "level", "text", "status", "fix", "auto", "manual"]);
      expect(c.status).toBe(c.level === "info" ? "skip" : c.level);
      if (c.status === "ok") expect([c.fix, c.auto, c.manual]).toEqual([null, false, null]);
    }
    const upgrade = data.checks.find((c: { fix: string }) => c.fix === "turno upgrade --finish");
    expect(upgrade).toMatchObject({ status: "warn", auto: true, manual: null });
    expect(data.checks.find((c: { text: string }) => c.text.startsWith("codex not found"))).toMatchObject({ status: "fail", fix: "npm install --global @openai/codex", auto: false });
    // Failures first, each command once.
    expect(data.next[0]).toBe("npm install --global @openai/codex");
    expect(data.next).toContain("turno upgrade --finish");
    expect(new Set(data.next).size).toBe(data.next.length);
    expect(data.next.indexOf("turno profile repair cx")).toBeLessThan(data.next.indexOf("turno upgrade --finish"));
  });

  it("--summary prints one line with the counts and the first fix", async () => {
    const io = fakeIo(sb.env);
    expect(await doctor(io, { summary: true })).toBe(1);
    expect(io.lines).toHaveLength(1);
    expect(io.lines[0]).toMatch(/^turno doctor: \d+ ok, \d+ warnings?, \d+ failures?, \d+ skipped; fix: npm install --global @openai\/codex$/);
    const sec = fakeIo(sb.env);
    await doctor(sec, { summary: true, security: true });
    expect(sec.lines[0]).toMatch(/^turno doctor --security: \d+ ok, .*; fix: /);
  });

  it("refuses --json with --summary", async () => {
    const io = fakeIo(sb.env);
    expect(await main(["doctor", "--json", "--summary"], io)).toBe(2);
    expect(io.errors.join("\n")).toContain("--json and --summary do not go together");
  });

  it("--fix runs the repairs, and exits 0 when only warnings are left", async () => {
    sb.write(".config/turno/config.toml", `[mcpd]\nport = ${await freePort()}\n\n[profiles.work]\n`);
    rmSync(join(sb.home, ".local/bin/claude-personal"));
    const io = fakeIo(sb.env);
    const code = await doctor(io, { fix: true });
    expect(code, io.lines.join("\n")).toBe(0);
    expect(io.lines).toContain("$ turno upgrade --finish");
    // After the repairs the screen does not offer them again.
    expect(io.lines.some((l) => l.startsWith("Next"))).toBe(false);
  });

  it("--security names the fix the same way", async () => {
    sb.write(".local/state/turno/usage/work.json", "{}", 0o644);
    const io = fakeIo(sb.env);
    await doctor(io, { security: true });
    const out = io.lines.join("\n");
    expect(io.lines[0]).toBe("Security");
    // The repair is doctor itself, so the line does not say so twice.
    expect(out).toMatch(/ {2}! {2}permissions: .*\n {5}fix: turno doctor --security --fix$/m);
    expect(out).toMatch(/MCP servers without an exact version: loose \(package loose-mcp@\^1\.2\.0\)\n {5}fix: turno mcp install loose$/m);
    expect(out).toMatch(/^Next {2}turno doctor --security --fix {2}repairs \d+ of \d+/m);
  });
});

describe("turno doctor follow-ups", () => {
  it("--fix runs turno mcp sync for a server that runs outside mcpd, and says what it changed", async () => {
    sb.write(".claude.json", JSON.stringify({ mcpServers: { gh: { command: "gh-mcp" }, own: { command: "own-mcp" } } }));
    const before = (await collectChecks(sb.env)).filter((c) => c.text.endsWith("runs outside mcpd"));
    expect(before.find((c) => c.text.startsWith("gh "))?.fix?.label).toBe("turno mcp sync");
    expect(before.find((c) => c.text.startsWith("own "))).toMatchObject({ hint: "turno mcp import" });
    const io = fakeIo(sb.env);
    await doctor(io, { fix: true });
    const out = io.lines.join("\n");
    expect(io.lines.filter((l) => l === "$ turno mcp sync")).toHaveLength(1);
    expect(out).toMatch(/~\/\.claude\.json\s+added .*updated gh/);
    const hub = JSON.parse(readFileSync(join(sb.home, ".claude.json"), "utf8")).mcpServers;
    expect(hub.gh.url).toMatch(/^http:\/\/127\.0\.0\.1:\d+\/mcp\/gh$/);
    expect(hub.own).toEqual({ command: "own-mcp" });
    expect(out).toContain("own runs outside mcpd");
    expect(out).not.toMatch(/gh runs outside mcpd/);
  });

  it("names a server that mcp.toml does not serve to the hub's profile instead of syncing it", async () => {
    sb.write(".config/turno/mcp.toml", '[server.gh]\ncommand = "gh-mcp"\nprofiles = ["work"]\n', 0o600);
    sb.write(".claude.json", JSON.stringify({ mcpServers: { gh: { command: "gh-mcp" } } }));
    const c = (await collectChecks(sb.env)).find((x) => x.text === "gh runs outside mcpd");
    expect(c).toMatchObject({ level: "warn", manual: "remove gh from ~/.claude.json, or serve it to profile default in mcp.toml" });
    expect(c?.fix).toBeUndefined();
  });

  it("reports env: and ${VAR} references mcp.toml cannot resolve here, never a value", async () => {
    sb.write(
      ".config/turno/mcp.toml",
      [
        '[server.gh]\ncommand = "gh-mcp"\nargs = ["--region=${REGION}", "--mode=${MODE:-fast}", "env:NOT_A_REF"]\nenv = { TOKEN = "env:GH_TOKEN", HOST = "env:GH_HOST:-github.com", KEY = "keychain:gh" }',
        '[server.gh.variant.work]\nenv = { TOKEN = "env:WORK_TOKEN" }',
        '[server.api]\nurl = "https://example.com/mcp"\nheaders = { Authorization = "env:API_TOKEN", "X-Region" = "${API_REGION}" }',
        '[server.open]\nurl = "https://example.com/open"\nheaders = { "X-Note" = "${NOT_PROXIED}" }',
      ].join("\n\n"),
      0o600,
    );
    const env = { ...sb.env, GH_TOKEN: "s3cr3t-value-1", API_TOKEN: "s3cr3t-value-2" };
    const mcp = (await collectChecks(env)).filter((c) => c.area === "mcp");
    expect(mcp.find((c) => c.text.startsWith("gh reads "))).toMatchObject({
      level: "warn",
      text: "gh reads REGION and WORK_TOKEN from mcpd's environment, and they are not set here",
    });
    // A proxied remote's headers are mcpd's to resolve; a direct remote's are the agent's.
    expect(mcp.find((c) => c.text.startsWith("api reads "))?.text).toBe("api reads API_REGION from mcpd's environment, and it is not set here");
    expect(mcp.find((c) => c.text.startsWith("gh reads "))?.manual).toContain("turno mcp daemon restart");
    expect(mcp.some((c) => c.text.startsWith("open reads "))).toBe(false);
    const io = fakeIo(env);
    await doctor(io, { json: true });
    const text = io.lines.join("\n");
    expect(text).not.toContain("s3cr3t-value");

    const ok = (await collectChecks({ ...env, REGION: "eu", WORK_TOKEN: "s3cr3t-value-3", API_REGION: "eu" })).filter((c) => c.area === "mcp");
    expect(ok.find((c) => c.text.startsWith("mcp.toml: every environment reference"))).toMatchObject({ level: "ok" });
    expect(JSON.stringify(ok)).not.toContain("s3cr3t-value");
  });

  it("checks the gateway token in synced configs without mcp-managed.json", async () => {
    const master = "m".repeat(43);
    sb.write(".local/state/turno/mcpd.token", `${master}\n`, 0o600);
    sb.write(".claude-work/.claude.json", JSON.stringify({ mcpServers: { gh: { type: "http", url: "http://127.0.0.1:1/mcp/gh", headers: { Authorization: `Bearer ${master}` } } } }));
    const c = tokenSyncCheck(sb.env);
    expect(c).toMatchObject({ level: "warn", fix: { label: "turno mcp sync" } });
    expect(c?.text).toContain("~/.claude-work/.claude.json");
    expect(c?.text).not.toContain(master);
  });
});
