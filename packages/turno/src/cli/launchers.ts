/** Every launcher turno writes carries this line; only marked files are ever overwritten. */
export const MARKER = "Generated by turno";
/** Markers of the bash claudio, of its predecessor, and of turno while it was called claudio. */
export const LEGACY_MARKERS = ["Generado por claudio", "Generado por claude-profile", "Generated by claudio"];

/** Helper launchers of the bash tool, kept working (editors may run claudio-auto) by pointing them at turno. */
const LEGACY_HELPERS = [
  ["claudio-auto", "auto"],
  ["claudio-open", "open"],
  ["claudio-navegador", "open"],
] as const;

/**
 * Hub folders shared by every profile. Launchers recreate them, so a cleanup that removed
 * an empty hub folder never leaves a profile with a dangling symlink.
 */
export const SHARED_DIRS = [
  "projects",
  "file-history",
  "plans",
  "tasks",
  "paste-cache",
  "session-env",
  "uploads",
  "dev-mods",
  "sessions",
  "skills",
  "commands",
  "agents",
  "hooks",
  "plugins",
  "output-styles",
  "workflows",
  "agent-memory",
  "rules",
  "themes",
  "state",
  "usage-data",
  "cache",
] as const;

export function executable(file: string): boolean {
  try {
    if (!statSync(file).isFile()) return false;
    accessSync(file, constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

/** Absolute path of a command found on PATH (or the command itself when it has a slash). */
export function findOnPath(cmd: string, env: NodeJS.ProcessEnv = process.env): string | undefined {
  if (cmd.includes("/")) return executable(cmd) ? cmd : undefined;
  for (const dir of (env.PATH ?? "").split(delimiter)) {
    if (!dir) continue;
    const file = join(dir, cmd);
    if (executable(file)) return file;
  }
  return undefined;
}

export const NPX_MESSAGE = "turno is running from npx's cache. Install it first: npm install --global turno-cli";

/** True when this turno runs from npm's npx cache, which npm may delete at any time. */
export function runningFromNpx(argv1: string | undefined = process.argv[1]): boolean {
  if (!argv1) return false;
  let file = argv1;
  try {
    file = realpathSync(argv1);
  } catch {
    /* keep the given path */
  }
  return file.includes("/_npx/");
}

/** Refuse a write that would keep a path into npx's cache (launchers, status line). */
export function refuseNpx(argv1: string | undefined = process.argv[1]): void {
  if (runningFromNpx(argv1)) throw new CliError(NPX_MESSAGE);
}

export function isGenerated(file: string): boolean {
  try {
    const text = readFileSync(file, "utf8");
    return [MARKER, ...LEGACY_MARKERS].some((m) => text.includes(m));
  } catch {
    return false;
  }
}

/** Escape text for a double-quoted shell word. */
const esc = (s: string) => s.replace(/(["\\$`])/g, "\\$1");

/** A launcher line that stops with a clear message when the agent is not installed. */
function requireAgent(agent: AgentId): string {
  const a = adapter(agent);
  return `command -v ${a.command} >/dev/null 2>&1 || { echo "turno: ${esc(a.command)} is not installed (${esc(a.install)})" >&2; exit 127; }`;
}

/**
 * The BROWSER export: claude.ai links open through turno-open, which needs `open` (macOS) or
 * `xdg-open` (Linux). Elsewhere the agent keeps its own browser handling.
 */
function browserLines(env: NodeJS.ProcessEnv, platform: NodeJS.Platform, comment: boolean): string[] {
  const works = platform === "darwin" || (platform === "linux" && Boolean(findOnPath("xdg-open", env)));
  if (!works) return [];
  const line = `export BROWSER=${shPath(join(paths(env).bin, "turno-open"), env)}`;
  return comment ? ["# claude.ai links (artifacts, login) open with this account: turno open.", line] : [line];
}

/** Double-quoted POSIX shell word; a path under HOME is written as "$HOME/...". */
export function shPath(p: string, env: NodeJS.ProcessEnv = process.env): string {
  const home = paths(env).home;
  if (p === home) return '"$HOME"';
  if (p.startsWith(home + "/")) return `"$HOME/${esc(p.slice(home.length + 1))}"`;
  return `"${esc(p)}"`;
}

/** The agent of a profile according to config.toml (Claude Code when the config is missing or broken). */
export function profileAgent(name: string, env: NodeJS.ProcessEnv = process.env): AgentId {
  try {
    return agentOf(name, loadConfig(env));
  } catch {
    return "claude";
  }
}

/** File name of a profile's launcher in ~/.local/bin: claude-<name>, codex-<name>, ... */
export function launcherName(name: string, agent: AgentId = "claude"): string {
  return `${adapter(agent).launcherPrefix}${name}`;
}

/** Text of the launcher of an agent other than Claude Code. */
function agentLauncherText(name: string, agent: AgentId, env: NodeJS.ProcessEnv, platform: NodeJS.Platform): string {
  const a = adapter(agent);
  const p = paths(env);
  const dir = shPath(agentProfileDir(name, agent, env), env);
  const hubDirs = a.sharedDirs.map((d) => shPath(join(agentHub(agent, env), d), env));
  const run = shPath(p.runDir, env);
  const runFile = run.slice(0, -1) + '/$$"';
  return [
    "#!/bin/sh",
    `# ${MARKER}: ${a.label} with the "${name}" account.`,
    `export ${a.homeEnv}=${dir}`,
    `export TURNO_PROFILE="${name}"`,
    `export TURNO_AGENT="${agent}"`,
    "export TURNO_SESSION_PID=$$",
    "# The session folder for the MCP gateway, base64url so any path fits in an HTTP header.",
    `TURNO_SESSION_CWD_B64="$(printf %s "$PWD" | base64 | tr -d '\\n=' | tr '+/' '-_')"`,
    "export TURNO_SESSION_CWD_B64",
    ...a.launcherEnv,
    ...(a.tokenFromEnv
      ? ["# The MCP gateway token, read by the agent from the environment (never written to its config).", `TURNO_MCPD_TOKEN="$(cat ${shPath(p.mcpdToken, env)} 2>/dev/null)"`, "export TURNO_MCPD_TOKEN"]
      : []),
    ...(hubDirs.length ? ["# If a cleanup removed an empty hub folder, the profile symlink would dangle.", `mkdir -p ${hubDirs.join(" ")}`] : []),
    ...browserLines(env, platform, false),
    "# exec keeps the PID, so turno sessions knows which account each session uses.",
    `mkdir -p ${run} && echo ${name} >${runFile} 2>/dev/null`,
    requireAgent(agent),
    `exec ${a.command} "$@"`,
    "",
  ].join("\n");
}

/** Text of a profile's launcher: claude-<name> by default, or the launcher of `agent`. */
export function launcherText(name: string, env: NodeJS.ProcessEnv = process.env, agent: AgentId = "claude", platform: NodeJS.Platform = process.platform): string {
  if (agent !== "claude") return agentLauncherText(name, agent, env, platform);
  const p = paths(env);
  const dirs = SHARED_DIRS.map((d) => shPath(join(p.hub, d), env)).join(" ");
  const run = shPath(p.runDir, env);
  const runFile = run.slice(0, -1) + '/$$"';
  return [
    "#!/bin/sh",
    `# ${MARKER}: Claude Code with the "${name}" account, sharing ${shPath(p.hub, env).slice(1, -1)}.`,
    `export CLAUDE_CONFIG_DIR="$HOME/.claude-${name}"`,
    `export TURNO_PROFILE="${name}"`,
    "export TURNO_SESSION_PID=$$",
    "# The session folder for the MCP gateway, base64url so any path fits in an HTTP header.",
    `TURNO_SESSION_CWD_B64="$(printf %s "$PWD" | base64 | tr -d '\\n=' | tr '+/' '-_')"`,
    "export TURNO_SESSION_CWD_B64",
    "# If a cleanup removed an empty hub folder, the profile symlink would dangle.",
    `mkdir -p ${dirs}`,
    ...browserLines(env, platform, true),
    "# exec keeps the PID, so turno sessions knows which account each session uses.",
    `mkdir -p ${run} && echo ${name} >${runFile} 2>/dev/null`,
    requireAgent("claude"),
    'exec claude "$@"',
    "",
  ].join("\n");
}

function writeScript(file: string, text: string): void {
  if (existsSync(file) && !isGenerated(file)) {
    throw new UsageError(`${file} already exists and was not generated by turno; leaving it alone`);
  }
  mkdirSync(join(file, ".."), { recursive: true });
  writeFileSync(file, text);
  chmodSync(file, 0o755);
}

/** Write the profile's launcher (claude-<name>, codex-<name>, ...). Refuses to overwrite a file turno did not generate. */
export function writeLauncher(name: string, env: NodeJS.ProcessEnv = process.env, agent: AgentId = profileAgent(name, env)): string {
  const file = join(paths(env).bin, launcherName(name, agent));
  writeScript(file, launcherText(name, env, agent));
  return file;
}

function sameFile(a: string, b: string): boolean {
  try {
    return realpathSync(a) === realpathSync(b);
  } catch {
    return false;
  }
}

/** Node version managers: a path inside one stops working when the active Node version changes. */
const VERSIONED = /\/(\.nvm|\.fnm|fnm\/node-versions|\.asdf\/installs|mise\/installs|\.nodenv\/versions|n\/versions)\//;

export interface TurnoCommand {
  /** Shell words that run turno. */
  words: string;
  /** Set when the words hold a path that may stop working. */
  warning?: string;
}

const quote = (s: string) => `"${esc(s)}"`;

function legacyScript(file: string): boolean {
  try {
    return readFileSync(file, "utf8").slice(0, 400).startsWith("#!/bin/bash");
  } catch {
    return false;
  }
}

/**
 * Shell words that run this turno, for launchers: the `turno` on PATH when there is one (as
 * found there, so a Homebrew or npm upgrade keeps working), else the path of the running CLI
 * entry with a warning, else plain `turno`.
 */
export function resolveTurnoCommand(env: NodeJS.ProcessEnv = process.env, argv1: string | undefined = process.argv[1]): TurnoCommand {
  const onPath = findOnPath("turno", env);
  if (onPath && !onPath.includes("/_npx/") && !legacyScript(onPath)) {
    const shown = tildify(onPath, env);
    return { words: quote(onPath), ...(VERSIONED.test(onPath) ? { warning: `wrote an absolute path (${shown}); it breaks if you switch Node versions` } : {}) };
  }
  const main = fileURLToPath(new URL("./main.js", import.meta.url));
  if (!argv1 || !sameFile(argv1, main)) return { words: "turno" };
  const real = realpathSync(argv1);
  const warning = `wrote an absolute path (${tildify(real, env)}) because turno is not on your PATH; it breaks if you switch Node versions or move this copy`;
  try {
    accessSync(real, constants.X_OK);
    return { words: quote(real), warning };
  } catch {
    return { words: `${quote(process.execPath)} ${quote(real)}`, warning };
  }
}

/** Shell words that run this turno (see resolveTurnoCommand). */
export function turnoCommand(argv1: string | undefined = process.argv[1], env: NodeJS.ProcessEnv = process.env): string {
  return resolveTurnoCommand(env, argv1).words;
}

function helperText(sub: "auto" | "open", why: string, turno: string): string {
  return ["#!/bin/sh", `# ${MARKER}: ${why}`, `exec ${turno} ${sub} "$@"`, ""].join("\n");
}

export function autoLauncherText(turno = turnoCommand()): string {
  return helperText("auto", "the agent with the account assigned to the folder (editors can use it as their Claude command).", turno);
}

export function openLauncherText(turno = turnoCommand()): string {
  return helperText("open", "Claude Code uses it as $BROWSER (turno open).", turno);
}

/**
 * Write turno-auto and turno-open. The claudio-auto and claudio-navegador left by the bash
 * tool are rewritten to run turno, so editors and sessions started before the switch keep working.
 * Returns the names written.
 */
export function writeHelperLaunchers(env: NodeJS.ProcessEnv = process.env, turno = turnoCommand()): string[] {
  const bin = paths(env).bin;
  const written: string[] = [];
  writeScript(join(bin, "turno-auto"), autoLauncherText(turno));
  written.push("turno-auto");
  writeScript(join(bin, "turno-open"), openLauncherText(turno));
  written.push("turno-open");
  for (const [name, sub] of LEGACY_HELPERS) {
    const legacy = join(bin, name);
    if (!existsSync(legacy) || !isGenerated(legacy)) continue;
    writeScript(legacy, sub === "auto" ? autoLauncherText(turno) : openLauncherText(turno));
    written.push(name);
  }
  return written;
}
