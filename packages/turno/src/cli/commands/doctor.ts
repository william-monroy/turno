export type Level = "ok" | "warn" | "fail" | "info";

export interface Fix {
  /** The command a person would run; equal labels run once. */
  label: string;
  run(io: Io): Promise<unknown> | unknown;
}

export interface Check {
  area: string;
  level: Level;
  text: string;
  fix?: Fix;
}

/** Whether a file is the original bash claudio script rather than this CLI. */
export function isLegacyScript(file: string): boolean {
  try {
    if (lstatSync(file).isSymbolicLink() && readlinkSync(file).endsWith(".js")) return false;
    const head = readFileSync(file, "utf8").slice(0, 400);
    return head.startsWith("#!/bin/bash") && head.includes("turno");
  } catch {
    return false;
  }
}

export async function mcpdStatus(env: NodeJS.ProcessEnv, config: Config | undefined): Promise<{ level: Level; text: string; running: boolean; port: number }> {
  const p = paths(env);
  let port = config?.mcpd.port ?? 47821;
  try {
    const n = Number.parseInt(readFileSync(p.mcpdPort, "utf8").trim(), 10);
    if (Number.isInteger(n) && n > 0) port = n;
  } catch {
    // no port file: the configured port
  }
  let token: string;
  try {
    token = readFileSync(p.mcpdToken, "utf8").trim();
  } catch {
    return { level: "info", running: false, port, text: `mcpd: no token at ${tildify(p.mcpdToken, env)} (not started yet: turno mcp daemon start)` };
  }
  try {
    const res = await fetch(`http://127.0.0.1:${port}/status`, {
      headers: { Authorization: `Bearer ${token}` },
      signal: AbortSignal.timeout(2000),
    });
    if (!res.ok) return { level: "warn", running: false, port, text: `mcpd on port ${port} answered HTTP ${res.status}` };
    return { level: "ok", running: true, port, text: `mcpd reachable on port ${port}` };
  } catch {
    return { level: "info", running: false, port, text: `mcpd not reachable on port ${port} (turno mcp daemon start)` };
  }
}

const repair = (name: string): Fix => ({
  label: `turno profile repair ${name}`,
  run: async (io) => (await import("./setup.js")).setupProfiles([name], io),
});

function isLinkTo(path: string, target: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink() && readlinkSync(path) === target;
  } catch {
    return false;
  }
}

function lexists(path: string): boolean {
  try {
    lstatSync(path);
    return true;
  } catch {
    return false;
  }
}

/** Launcher, folder, hub links and command of a profile of another agent (ADR 0013). */
async function agentProfileChecks(name: string, agent: AgentId, env: NodeJS.ProcessEnv): Promise<Check[]> {
  const a = adapter(agent);
  const area = `profile ${name}`;
  const out: Check[] = [];
  const launcher = join(paths(env).bin, launcherName(name, agent));
  if (!existsSync(launcher)) out.push({ area, level: "fail", text: `profile ${name}: no launcher ${tildify(launcher, env)}`, fix: repair(name) });
  else if (!isGenerated(launcher)) out.push({ area, level: "fail", text: `profile ${name}: ${tildify(launcher, env)} was not generated by turno` });
  else if (readFileSync(launcher, "utf8") !== launcherText(name, env, agent)) out.push({ area, level: "warn", text: `profile ${name}: launcher is out of date`, fix: repair(name) });
  else out.push({ area, level: "ok", text: `profile ${name}: ${a.label} launcher ok` });
  const dir = agentProfileDir(name, agent, env);
  if (!existsSync(dir)) {
    out.push({ area, level: "fail", text: `profile ${name}: ${tildify(dir, env)} does not exist`, fix: repair(name) });
    return out;
  }
  const hub = agentHub(agent, env);
  for (const item of [...a.sharedDirs, ...a.sharedFiles]) {
    const path = join(dir, item);
    const target = join(hub, item);
    if (isLinkTo(path, target)) continue;
    if (existsSync(path)) out.push({ area, level: "warn", text: `profile ${name}: ${item} is a local copy, not shared`, fix: repair(name) });
    else if (existsSync(target)) out.push({ area, level: "warn", text: `profile ${name}: missing link for ${item}`, fix: repair(name) });
  }
  if (agent === "codex") {
    let store: unknown;
    try {
      store = (parseToml(readFileSync(join(dir, "config.toml"), "utf8")) as Record<string, unknown>).cli_auth_credentials_store;
    } catch {
      store = undefined;
    }
    if (store !== "file") out.push({ area, level: "warn", text: `profile ${name}: Codex may keep the login in the shared Keychain (cli_auth_credentials_store is not "file")`, fix: repair(name) });
  }
  if (!findOnPath(a.command, env)) out.push({ area, level: "warn", text: `profile ${name}: ${a.command} is not on PATH (${a.install})` });
  return out;
}

/** Shared links and unclassified items of one profile folder. */
async function profileChecks(name: string, env: NodeJS.ProcessEnv): Promise<Check[]> {
  const { PER_ACCOUNT, SHARED_DIRS, SHARED_FILES } = await import("./setup.js");
  const p = paths(env);
  const dir = profileDir(name, env);
  const out: Check[] = [];
  const area = `profile ${name}`;
  const launcher = join(p.bin, `claude-${name}`);
  if (!existsSync(launcher)) out.push({ area, level: "fail", text: `profile ${name}: no launcher ${tildify(launcher, env)}`, fix: repair(name) });
  else if (!isGenerated(launcher)) out.push({ area, level: "fail", text: `profile ${name}: ${tildify(launcher, env)} was not generated by turno` });
  else if (!readFileSync(launcher, "utf8").includes(MARKER)) out.push({ area, level: "warn", text: `profile ${name}: launcher from the bash claudio`, fix: repair(name) });
  else out.push({ area, level: "ok", text: `profile ${name}: launcher ok` });
  if (!existsSync(dir)) {
    out.push({ area, level: "fail", text: `profile ${name}: ${tildify(dir, env)} does not exist`, fix: repair(name) });
    return out;
  }
  const shared = [...SHARED_DIRS, ...SHARED_FILES] as string[];
  const problems: string[] = [];
  for (const item of shared) {
    const path = join(dir, item);
    const target = join(p.hub, item);
    if (isLinkTo(path, target)) continue;
    if (existsSync(path)) problems.push(`${item} is a local copy, not shared`);
    else if (existsSync(target)) problems.push(`missing link for ${item}`);
  }
  for (const pr of problems) out.push({ area, level: "warn", text: `profile ${name}: ${pr}`, fix: repair(name) });
  const known = new Set<string>([...shared, ...PER_ACCOUNT]);
  let entries: string[] = [];
  try {
    entries = readdirSync(dir).sort();
  } catch {
    entries = [];
  }
  for (const item of entries) {
    if (known.has(item) || !lexists(join(dir, item))) continue;
    if (/^(\.aside-|\.aparte-|\.claude\.json\.|history\.jsonl\.)/.test(item)) continue;
    out.push({ area, level: "info", text: `profile ${name}: ${item} is new and unclassified: decide whether to share it` });
  }
  return out;
}

export async function collectChecks(env: NodeJS.ProcessEnv): Promise<Check[]> {
  const p = paths(env);
  const checks: Check[] = [];
  const add = (area: string, level: Level, text: string, fix?: Fix) => checks.push({ area, level, text, ...(fix ? { fix } : {}) });

  const major = Number(process.versions.node.split(".")[0]);
  add("system", major >= 20 ? "ok" : "fail", `node ${process.versions.node}${major >= 20 ? "" : " (turno needs >= 20)"}`);
  const claude = findOnPath("claude", env);
  add("system", claude ? "ok" : "fail", claude ? `claude at ${tildify(claude, env)}` : "claude not found on PATH");
  const chrome = env.TURNO_CHROME_APP || "/Applications/Google Chrome.app";
  add("system", existsSync(chrome) ? "ok" : "warn", existsSync(chrome) ? "Google Chrome installed" : "Google Chrome not found: claude.ai links open in the default browser");

  const { recordedVersion, finishUpgrade } = await import("./upgrade.js");
  const version = packageInfo().version;
  const recorded = recordedVersion(env);
  if (recorded && recorded !== version) {
    add("turno", "warn", `turno ${version} runs, but ${recorded} set up the launchers`, { label: "turno upgrade --finish", run: (io) => finishUpgrade(io) });
  } else add("turno", "ok", `turno ${version}`);
  const newer = availableUpdate(env);
  if (newer) add("turno", "info", `turno ${newer} is available (turno upgrade)`);

  let config: Config | undefined;
  try {
    config = loadConfig(env);
    if (existsSync(p.configFile)) add("config", "ok", `${tildify(p.configFile, env)} parses`);
    else if (migrationPending(env)) add("config", "info", `no ${tildify(p.configFile, env)} yet: turno migrate imports the bash config`);
    else add("config", "info", `no ${tildify(p.configFile, env)} (defaults)`);
  } catch (err) {
    add("config", "fail", (err as Error).message);
  }
  try {
    const m = loadManifest(env);
    if (existsSync(p.mcpFile)) add("config", "ok", `${tildify(p.mcpFile, env)} parses (${Object.keys(m.servers).length} servers)`);
    else add("config", "info", `no ${tildify(p.mcpFile, env)} yet (turno mcp import)`);
  } catch (err) {
    add("config", "fail", (err as Error).message);
  }
  if (existsSync(p.accountsFile)) {
    try {
      loadRegistry(env);
      add("config", "ok", `${tildify(p.accountsFile, env)} parses`);
    } catch (err) {
      add("config", "fail", (err as Error).message);
    }
  }

  if (config) {
    const profiles = listProfiles(config, env);
    if (profiles.length === 0) add("profiles", "info", "no profiles yet (turno profile add <name>)");
    for (const name of profiles) {
      const agent = agentOf(name, config);
      checks.push(...(agent === "claude" ? await profileChecks(name, env) : await agentProfileChecks(name, agent, env)));
    }
  }
  const legacyBin = join(p.bin, "claudio");
  if (isLegacyScript(legacyBin)) add("turno", "info", `${tildify(legacyBin, env)} is still the bash claudio (the cutover points it at turno)`);

  try {
    const { bypassingServers } = await import("./mcp.js");
    const b = await bypassingServers(env);
    for (const s of b.plugins) add("mcp", "info", `plugin server ${s.plugin}/${s.name} starts in every session (turno mcp doctor)`);
    for (const d of b.direct) add("mcp", "warn", `${d.name} runs outside mcpd (${d.inManifest ? "turno mcp sync" : "turno mcp import"})`);
  } catch {
    /* a broken mcp.toml is reported above */
  }

  const settings = join(p.hub, "settings.json");
  const line = currentStatusLine(settings);
  if (isTurnoStatusLine(line)) add("look", "ok", "status line: turno statusline");
  else add("look", "info", `status line: ${line ? `\`${line.command}\`` : "none"} in ${tildify(settings, env)} (turno ui install)`);
  const fontDir = userFontDir(env);
  if (fontDir) {
    const fonts = checkFonts(FALLBACK, fontDir);
    const have = fonts.filter((f) => f.state === "installed").length;
    if (have === fonts.length) add("look", "ok", `font: ${FALLBACK.family} installed`);
    else add("look", "info", `font: ${FALLBACK.family} ${have}/${fonts.length} files in ${tildify(fontDir, env)} (turno ui install)`);
  }

  const mcpd = await mcpdStatus(env, config);
  add("mcpd", mcpd.level, mcpd.text);
  return checks;
}

function report(io: Io, c: Check): void {
  const tag = { ok: paint(io, "ok  ", "32"), warn: paint(io, "warn", "33"), fail: paint(io, "FAIL", "31"), info: paint(io, "info", "2") }[c.level];
  io.out(`${tag}  ${c.text}${c.fix && c.level !== "ok" ? paint(io, `  [fix: ${c.fix.label}]`, "2") : ""}`);
}

export async function doctor(io: Io, opts: { fix?: boolean; json?: boolean } = {}): Promise<number> {
  let checks = await collectChecks(io.env);
  if (opts.fix) {
    const fixes = new Map<string, Fix>();
    for (const c of checks) if (c.fix && (c.level === "warn" || c.level === "fail")) fixes.set(c.fix.label, c.fix);
    for (const f of fixes.values()) {
      if (!opts.json) io.out(paint(io, `$ ${f.label}`, "1"));
      await f.run(opts.json ? { ...io, out: () => {} } : io);
    }
    if (fixes.size) {
      if (!opts.json) io.out("");
      checks = await collectChecks(io.env);
    } else if (!opts.json) io.out("Nothing to fix automatically.\n");
  }
  const failed = checks.some((c) => c.level === "fail");
  if (opts.json) {
    printJson(io.out, { ok: !failed, checks: checks.map(({ fix, ...c }) => ({ ...c, fix: fix?.label ?? null })) });
    return failed ? 1 : 0;
  }
  for (const c of checks) report(io, c);
  const fixable = checks.filter((c) => c.fix && (c.level === "warn" || c.level === "fail")).length;
  if (fixable && !opts.fix) io.out(`\n${fixable} can be fixed with: turno doctor --fix`);
  return failed ? 1 : 0;
}

export const command: Command = {
  summary: "check everything (system, config, profiles, MCP, look, mcpd) and fix what is safe to fix",
  usage: [
    "Usage: turno doctor [--fix] [--json]",
    "",
    "Exits 1 when a hard check fails. --fix runs the repair each failed check names (relink a",
    "profile, rewrite launchers, finish an upgrade), then checks again.",
  ].join("\n"),
  flags: ["--fix", "--json"],
  async run(args, io) {
    const p = parseFlags(args, { fix: { type: "boolean" }, ...JSON_FLAG }, 0);
    return doctor(io, { fix: bool(p, "fix"), json: bool(p, "json") });
  },
};
