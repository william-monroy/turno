import { accessSync, chmodSync, constants, existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { paths } from "../core/paths.js";
import { UsageError } from "./io.js";

/** Every launcher claudio writes carries this line; only marked files are ever overwritten. */
export const MARKER = "Generated by claudio";
/** Markers of the original bash tool and of its predecessor. */
export const LEGACY_MARKERS = ["Generado por claudio", "Generado por claude-profile"];

/**
 * Hub folders shared by every profile. Launchers recreate them, so a cleanup that removed
 * an empty hub folder never leaves a profile with a dangling symlink.
 */
export const SHARED_DIRS = [
  "projects",
  "file-history",
  "plans",
  "tasks",
  "paste-cache",
  "session-env",
  "uploads",
  "dev-mods",
  "sessions",
  "skills",
  "commands",
  "agents",
  "hooks",
  "plugins",
  "output-styles",
  "workflows",
  "agent-memory",
  "rules",
  "themes",
  "state",
  "usage-data",
  "cache",
] as const;

export function isGenerated(file: string): boolean {
  try {
    const text = readFileSync(file, "utf8");
    return [MARKER, ...LEGACY_MARKERS].some((m) => text.includes(m));
  } catch {
    return false;
  }
}

/** Double-quoted POSIX shell word; a path under HOME is written as "$HOME/...". */
export function shPath(p: string, env: NodeJS.ProcessEnv = process.env): string {
  const home = paths(env).home;
  const esc = (s: string) => s.replace(/(["\\$`])/g, "\\$1");
  if (p === home) return '"$HOME"';
  if (p.startsWith(home + "/")) return `"$HOME/${esc(p.slice(home.length + 1))}"`;
  return `"${esc(p)}"`;
}

/** Text of the claude-<name> launcher. */
export function launcherText(name: string, env: NodeJS.ProcessEnv = process.env): string {
  const p = paths(env);
  const dirs = SHARED_DIRS.map((d) => shPath(join(p.hub, d), env)).join(" ");
  const run = shPath(p.runDir, env);
  const runFile = run.slice(0, -1) + '/$$"';
  return [
    "#!/bin/sh",
    `# ${MARKER}: Claude Code with the "${name}" account, sharing ${shPath(p.hub, env).slice(1, -1)}.`,
    `export CLAUDE_CONFIG_DIR="$HOME/.claude-${name}"`,
    `export CLAUDIO_PROFILE="${name}"`,
    "export CLAUDIO_SESSION_PID=$$",
    "# If a cleanup removed an empty hub folder, the profile symlink would dangle.",
    `mkdir -p ${dirs}`,
    "# claude.ai links (artifacts, login) open with this account: claudio open.",
    `export BROWSER=${shPath(join(p.bin, "claudio-open"), env)}`,
    "# exec keeps the PID, so claudio sessions knows which account each session uses.",
    `mkdir -p ${run} && echo ${name} >${runFile} 2>/dev/null`,
    'exec claude "$@"',
    "",
  ].join("\n");
}

function writeScript(file: string, text: string): void {
  if (existsSync(file) && !isGenerated(file)) {
    throw new UsageError(`${file} already exists and was not generated by claudio; leaving it alone`);
  }
  mkdirSync(join(file, ".."), { recursive: true });
  writeFileSync(file, text);
  chmodSync(file, 0o755);
}

/** Write <bin>/claude-<name>. Refuses to overwrite a file claudio did not generate. */
export function writeLauncher(name: string, env: NodeJS.ProcessEnv = process.env): string {
  const file = join(paths(env).bin, `claude-${name}`);
  writeScript(file, launcherText(name, env));
  return file;
}

function sameFile(a: string, b: string): boolean {
  try {
    return realpathSync(a) === realpathSync(b);
  } catch {
    return false;
  }
}

/**
 * Shell words that run this claudio: the real path of the running CLI entry when it is
 * this package's main module, else `claudio` from PATH.
 */
export function claudioCommand(argv1: string | undefined = process.argv[1]): string {
  const main = fileURLToPath(new URL("./main.js", import.meta.url));
  if (!argv1 || !sameFile(argv1, main)) return "claudio";
  const real = realpathSync(argv1);
  const q = (s: string) => `"${s.replace(/(["\\$`])/g, "\\$1")}"`;
  try {
    accessSync(real, constants.X_OK);
    return q(real);
  } catch {
    return `${q(process.execPath)} ${q(real)}`;
  }
}

function helperText(sub: "auto" | "open", why: string, claudio: string): string {
  return ["#!/bin/sh", `# ${MARKER}: ${why}`, `exec ${claudio} ${sub} "$@"`, ""].join("\n");
}

export function autoLauncherText(claudio = claudioCommand()): string {
  return helperText("auto", "Claude Code with the account assigned to the project (Orca uses it as its Claude command).", claudio);
}

export function openLauncherText(claudio = claudioCommand()): string {
  return helperText("open", "Claude Code uses it as $BROWSER (claudio open).", claudio);
}

/**
 * Write claudio-auto and claudio-open. A claudio-navegador left by the bash tool is
 * rewritten as claudio-open, so sessions started before the switch keep opening links.
 * Returns the names written.
 */
export function writeHelperLaunchers(env: NodeJS.ProcessEnv = process.env, claudio = claudioCommand()): string[] {
  const bin = paths(env).bin;
  const written: string[] = [];
  writeScript(join(bin, "claudio-auto"), autoLauncherText(claudio));
  written.push("claudio-auto");
  writeScript(join(bin, "claudio-open"), openLauncherText(claudio));
  written.push("claudio-open");
  const legacy = join(bin, "claudio-navegador");
  if (existsSync(legacy) && isGenerated(legacy)) {
    writeScript(legacy, openLauncherText(claudio));
    written.push("claudio-navegador");
  }
  return written;
}
