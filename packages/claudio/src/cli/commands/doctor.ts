type Level = "ok" | "warn" | "fail" | "info";

function report(io: Io, level: Level, text: string): void {
  const tag = { ok: paint(io, "ok  ", "32"), warn: paint(io, "warn", "33"), fail: paint(io, "FAIL", "31"), info: paint(io, "info", "2") }[level];
  io.out(`${tag}  ${text}`);
}

/** Whether a file is the original bash claudio script rather than this CLI. */
export function isLegacyScript(file: string): boolean {
  try {
    if (lstatSync(file).isSymbolicLink() && readlinkSync(file).endsWith(".js")) return false;
    const head = readFileSync(file, "utf8").slice(0, 400);
    return head.startsWith("#!/bin/bash") && head.includes("claudio");
  } catch {
    return false;
  }
}

async function mcpdStatus(env: NodeJS.ProcessEnv, config: Config | undefined): Promise<{ level: Level; text: string }> {
  const p = paths(env);
  let port = config?.mcpd.port ?? 47821;
  try {
    const n = Number.parseInt(readFileSync(p.mcpdPort, "utf8").trim(), 10);
    if (Number.isInteger(n) && n > 0) port = n;
  } catch {
    // no port file: the configured port
  }
  let token: string;
  try {
    token = readFileSync(p.mcpdToken, "utf8").trim();
  } catch {
    return { level: "info", text: `mcpd: no token at ${tildify(p.mcpdToken, env)} (not started yet: claudio mcpd start)` };
  }
  try {
    const res = await fetch(`http://127.0.0.1:${port}/status`, {
      headers: { Authorization: `Bearer ${token}` },
      signal: AbortSignal.timeout(2000),
    });
    if (!res.ok) return { level: "warn", text: `mcpd on port ${port} answered HTTP ${res.status}` };
    return { level: "ok", text: `mcpd reachable on port ${port}` };
  } catch {
    return { level: "info", text: `mcpd not reachable on port ${port} (claudio mcpd start)` };
  }
}

export async function doctor(io: Io): Promise<number> {
  const env = io.env;
  const p = paths(env);
  let failed = false;
  const check = (level: Level, text: string) => {
    if (level === "fail") failed = true;
    report(io, level, text);
  };

  const major = Number(process.versions.node.split(".")[0]);
  check(major >= 20 ? "ok" : "fail", `node ${process.versions.node}${major >= 20 ? "" : " (claudio needs >= 20)"}`);

  const claude = findOnPath("claude", env);
  check(claude ? "ok" : "fail", claude ? `claude at ${tildify(claude, env)}` : "claude not found on PATH");

  const chrome = env.CLAUDIO_CHROME_APP || "/Applications/Google Chrome.app";
  check(existsSync(chrome) ? "ok" : "warn", existsSync(chrome) ? "Google Chrome installed" : "Google Chrome not found: claude.ai links open in the default browser");

  let config: Config | undefined;
  try {
    config = loadConfig(env);
    check(existsSync(p.configFile) ? "ok" : "info", existsSync(p.configFile) ? `${tildify(p.configFile, env)} parses` : `no ${tildify(p.configFile, env)} (defaults; claudio migrate imports the old one)`);
  } catch (err) {
    check("fail", (err as Error).message);
  }
  try {
    const m = loadManifest(env);
    if (existsSync(p.mcpFile)) check("ok", `${tildify(p.mcpFile, env)} parses (${Object.keys(m.servers).length} servers)`);
    else check("info", `no ${tildify(p.mcpFile, env)} yet (claudio mcp import)`);
  } catch (err) {
    check("fail", (err as Error).message);
  }

  if (config) {
    const profiles = listProfiles(config, env);
    if (profiles.length === 0) check("info", "no profiles yet (claudio setup <profile>)");
    for (const name of profiles) {
      const launcher = join(p.bin, `claude-${name}`);
      if (!existsSync(launcher)) check("fail", `profile ${name}: no launcher ${tildify(launcher, env)} (claudio setup ${name})`);
      else if (!isGenerated(launcher)) check("fail", `profile ${name}: ${tildify(launcher, env)} was not generated by claudio`);
      else if (!readFileSync(launcher, "utf8").includes(MARKER)) check("warn", `profile ${name}: launcher from the bash claudio (claudio setup ${name} regenerates it)`);
      else check("ok", `profile ${name}: launcher ok`);
    }
  }

  const binClaudio = join(p.bin, "claudio");
  if (isLegacyScript(binClaudio)) check("info", `${tildify(binClaudio, env)} is still the legacy bash script`);

  const mcpd = await mcpdStatus(env, config);
  check(mcpd.level, mcpd.text);
  return failed ? 1 : 0;
}

export const command: Command = {
  summary: "check the environment (node, claude, Chrome, config, launchers, mcpd)",
  usage: "Usage: claudio doctor\n\nExits 1 when a hard check fails.",
  async run(_args, io) {
    return doctor(io);
  },
};
