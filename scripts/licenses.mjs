#!/usr/bin/env node
// Check the licenses of every production dependency and write THIRD_PARTY_NOTICES.md.
//   node scripts/licenses.mjs           fail if a dependency has a denied or unknown license,
//                                       or if THIRD_PARTY_NOTICES.md is out of date
//   node scripts/licenses.mjs --write   regenerate THIRD_PARTY_NOTICES.md
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const FILE = join(root, "THIRD_PARTY_NOTICES.md");
const OWN = new Set(["turno", "turno-browser", "turno-fonts"]);

// Licenses a dependency may carry. Anything else (GPL, AGPL, LGPL, SSPL, UNLICENSED, unknown)
// fails the check until someone looks at it and, if it is fine, adds it here.
const ALLOWED = new Set([
  "MIT",
  "ISC",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "0BSD",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "Unlicense",
  "Python-2.0",
]);

function allowed(expr) {
  // "(MIT OR Apache-2.0)" passes when any alternative does; "A AND B" needs both.
  const clean = expr.replace(/[()]/g, "").trim();
  if (clean.includes(" OR ")) return clean.split(" OR ").some((e) => allowed(e));
  if (clean.includes(" AND ")) return clean.split(" AND ").every((e) => allowed(e));
  return ALLOWED.has(clean);
}

const out = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: root, encoding: "utf8" });
const byLicense = JSON.parse(out.slice(out.indexOf("{")));
const deps = [];
for (const [license, list] of Object.entries(byLicense)) {
  for (const d of list) {
    if (OWN.has(d.name)) continue;
    deps.push({ name: d.name, versions: d.versions, license, homepage: d.homepage ?? "", author: d.author ?? "" });
  }
}
deps.sort((a, b) => a.name.localeCompare(b.name));

const denied = deps.filter((d) => !allowed(d.license));

const lines = [
  "# Third-party notices",
  "",
  "turno is under the Apache License 2.0 (see `LICENSE` and `NOTICE`). Its npm packages do not",
  "bundle their dependencies: npm installs each one from the registry with its own license file.",
  "This list is generated by `node scripts/licenses.mjs --write` from `pnpm licenses list --prod`.",
  "",
  "The fonts in `packages/fonts` are bundled; their licenses and attributions are in",
  "`packages/fonts/LICENSE.txt`.",
  "",
  "| Package | Version | License | Homepage |",
  "|---|---|---|---|",
  ...deps.map((d) => `| ${d.name} | ${d.versions.join(", ")} | ${d.license} | ${d.homepage} |`),
  "",
];
const text = lines.join("\n");

if (process.argv.includes("--write")) {
  writeFileSync(FILE, text);
  console.log(`wrote ${deps.length} dependencies to THIRD_PARTY_NOTICES.md`);
} else {
  let current = "";
  try {
    current = readFileSync(FILE, "utf8");
  } catch {}
  if (current !== text) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run node scripts/licenses.mjs --write");
    process.exitCode = 1;
  }
}
for (const d of denied) console.error(`license not allowed: ${d.name}@${d.versions.join(",")} (${d.license})`);
if (denied.length) process.exitCode = 1;
else console.log(`ok  ${deps.length} production dependencies, all with allowed licenses`);
